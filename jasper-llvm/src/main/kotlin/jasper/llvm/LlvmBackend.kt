/* ============================================================================
 * LlvmBackend.kt —— 实验性 LLVM IR 文本后端（backend 层 / jasper-llvm 子项目）
 * ============================================================================
 *
 * 职责：
 *   把 AST 声明列表**直接**渲染成 LLVM IR 文本，并落盘为 `<package>.ll`。
 *   这是后端层的一个**占位 / 演示实现**，目的只是打通「AST -> 文本 IR」的
 *   最小闭环；请勿据此判断 Jasper 的 LLVM 支持成熟度。
 *
 * 所属层次：
 *   backend 层（LAYER_RANK rank=2；路径含 /jasper/llvm/ 即判为 backend）。
 *   只依赖 jasper.ast，不依赖 checker/translator/compiler 等任何上层，
 *   因此是这条流水线上的一枚**叶子**。
 *
 * 与谁协作：
 *   - 上游：由编译编排层在拿到（已校验 / 已翻译的）AST 后调用 generate。
 *   - 下游：产物是纯文本 .ll，交给外部 LLVM 工具链（clang/llc 等）消费；
 *     本文件不调用、不链接任何 LLVM 库，也不做 IR 校验。
 *
 * 对外契约：
 *   - generate(packageName, declarations, outputDir) 无返回值；把 IR 写到
 *     outputDir/`packageName?.replace('.', '/') ?: "output"`.ll，父目录不存在
 *     时自动 mkdirs；
 *   - packageName 为 null 时文件名回退为 "output"，包名中的 '.' 转成目录分隔。
 *
 * 扩展点 / 已知限制（重要，反映当前实现远未完整）：
 *   - 只处理 JasFunction 及其内部出现的 JasReturn；其它声明、语句、表达式
 *     一律经 when 的 else 分支**静默跳过**，故生成的 IR 语义远不完整；
 *   - target triple 目前**硬编码**为 x86_64-pc-windows-msvc，未参数化，
 *     换平台必须改此处（已知局限）；
 *   - 类型映射与常量取值均为启发式，无法判定的表达式退化为 `0`；
 *   - 本后端**未采用 Strategy（可替换后端）抽象**：若将来引入，变化点应隔离
 *     在「如何渲染某类声明 / 表达式」的方法（如 generateFunction、llvmType）
 *     上，而不要散落进 generate/generateIr 主流程；当前它只是与
 *     JvmIrBackend 并列的另一个落盘实现。
 * ========================================================================= */

package jasper.llvm

import jasper.ast.*
import java.io.File
import java.nio.file.Path

/**
 * 做什么：LLVM IR 文本后端。把一组 JasDeclaration 渲染为 LLVM IR 文本并写成
 *   `.ll` 文件；当前仅覆盖「函数 + return」这一最小子集，属占位实现。
 *
 * 什么时候用：需要在 JVM 字节码之外另产出一份 LLVM IR 文本时（实验 / 演示）。
 *   什么时候不该用：不要把它当作可用的 LLVM 后端——不支持的语法会被**静默
 *   丢弃**，产出的 IR 不保证语义等价。
 *
 * 前置条件：declarations 是（通常已校验 / 已翻译的）AST 节点列表；outputDir
 *   可写，父目录会自动创建。
 *
 * 失败模式：本类几乎不做错误处理——不支持的结构静默忽略；写文件失败则抛
 *   IOException，交由调用方处理，本类不产生编译诊断。
 *
 * 为什么这样设计：作为最小占位实现，刻意保持「输入 AST -> 输出文本」的单向、
 *   无状态转换，便于后续替换或扩展而无需改动上游。
 */
class LlvmBackend {
    /**
     * 生成 LLVM IR 文本并落盘。
     *
     * 做什么：先调用 generateIr 得到 IR 文本，再按包名推导输出路径并写文件。
     *
     * 什么时候用：编译编排层决定要产出 LLVM IR 时调用一次。
     *
     * 前置条件：outputDir 可写；declarations 中只有 JasFunction 会被处理。
     *
     * 失败模式：父目录自动 mkdirs；写失败抛 IOException；不支持的声明被静默
     *   跳过（no-op）而非报错。
     */
    fun generate(
        packageName: String?,
        declarations: List<JasDeclaration>,
        outputDir: Path
    ) {
        val irCode = generateIr(declarations)
        // 包名 a.b.c -> 相对路径 a/b/c；为 null 时回退到 "output"。
        val filename = (packageName ?: "output").replace('.', '/')
        val file = outputDir.resolve("$filename.ll").toFile()
        // 父目录可能不存在（例如包 a/b），显式递归创建。
        file.parentFile.mkdirs()
        file.writeText(irCode)
    }

    /**
     * 把声明列表渲染成完整 IR 文本。
     *
     * 做什么：先写死模块级头部（来源注释、target triple、printf 外部声明），
     *   再逐个声明分派；只有 JasFunction 会被真正生成。
     *
     * 为什么只遍历函数：当前后端有意只支持「函数 + return」，其余声明（类 /
     *   接口 / 枚举 / 属性 / 导入等）落到 else 分支被跳过——这是**已知边界**，
     *   不是遗漏的错误处理。
     */
    private fun generateIr(declarations: List<JasDeclaration>): String {
        val sb = StringBuilder()
        // 首行写来源标记，便于人工辨别 .ll 文件的出身。
        sb.appendLine("; Generated by Jasper LLVM Backend")
        // target triple 目前硬编码为 Windows x86-64 MSVC：未参数化，换平台必须改
        // 这一行，且类型宽度 / 调用约定并不会随之自动调整（已知局限）。
        sb.appendLine("target triple = \"x86_64-pc-windows-msvc\"")
        sb.appendLine()

        // Declare external functions
        // 预置外部函数声明：目前只声明 printf，供后续（尚未实现的）调用使用。
        sb.appendLine("declare i32 @printf(i8*, ...)")
        sb.appendLine()

        // 只遍历顶层声明，且仅分派 JasFunction；其余声明落到 else 分支被跳过。
        for (decl in declarations) {
            when (decl) {
                is JasFunction -> generateFunction(sb, decl)
                else -> {} // Skip non-functions for now
            }
        }
        return sb.toString()
    }

    /**
     * 渲染单个函数定义。
     *
     * 做什么：把返回类型与各参数类型映射成 LLVM 类型，写 `define ... { entry:`
     *   函数头，渲染函数体，最后补一条默认 `ret`。
     *
     * 什么时候用：仅由 generateIr 对每个 JasFunction 调用。
     *
     * 边界 / 已知局限：不写参数名与属性；函数体为空时也会生成默认 ret；对
     *   非 void 的返回类型，默认返回常量 `0`（占位，语义不保证）。
     */
    private fun generateFunction(sb: StringBuilder, func: JasFunction) {
        val returnType = llvmType(func.returnType)
        // 参数逐个映射为 LLVM 类型，用 ", " 连接；暂不处理参数名与可变参数。
        val paramTypes = func.parameters.joinToString(", ") { llvmType(it.type) }

        // 函数头：define <返回类型> @<名字>(<参数类型...>) { ；后接唯一基本块 entry。
        sb.appendLine("define $returnType @${func.name}($paramTypes) {")
        sb.appendLine("  entry:")

        val body = func.body
        if (body != null) {
            generateBlock(sb, body, "  ")
        }

        // Default return
        // 无论函数体是否已显式 return，都在末尾补一条默认返回，保证函数以终结
        // 指令收尾。注意副作用：显式 return 之后会产生不可达的死代码，且对
        // void 之外的返回类型回退值为常量 0（仅占位，已知局限）。
        sb.appendLine("  ret $returnType 0")
        sb.appendLine("}")
        sb.appendLine()
    }

    /**
     * 渲染语句块中的 return 语句。
     *
     * 做什么：只识别 JasReturn；带返回值时发 `ret <类型> <值>`，无返回值的
     *   return（含 void 函数）**不发任何指令**，依赖 generateFunction 末尾的
     *   默认 ret 兜底。
     *
     * 什么时候用：仅由 generateFunction 对函数体调用。
     *
     * 边界：其它语句类型（赋值 / 分支 / 循环 / 调用等）一律静默忽略，不生成 IR。
     */
    private fun generateBlock(sb: StringBuilder, block: JasBlock, indent: String) {
        // 只扫一层 statements；嵌套块（if/while 的 body 等）不会被递归进入。
        for (stmt in block.statements) {
            when (stmt) {
                is JasReturn -> {
                    val value = stmt.value
                    if (value != null) {
                        // llvmValue 取字面量文本、llvmType 推断类型；两者都无法判定
                        // 时会分别退化为默认值（见各自注释）。
                        sb.appendLine("$indent  ret ${llvmType(value)} ${llvmValue(value)}")
                    }
                }
                else -> {}
            }
        }
    }

    /**
     * JasType -> LLVM 类型字符串的映射。
     *
     * 做什么：把标量 / 单元 / 字符串 / Any / 命名类型映射到 LLVM IR 类型标记。
     *
     * 映射规则：int32->i32、int64->i64、float32->float、float64->double、
     *   bool->i1、byte->i8；单元类型->void；字符串 / Any / 命名类型统一退化为
     *   i8*（不透明字节指针，尚无真实内存布局）；其它未知类型兜底 i32。
     *
     * 已知局限：`else -> "i32"` 的兜底会把未识别的标量名与所有未覆盖情形静默
     *   当成 i32，可能产出语义错误的 IR 而非报错。
     */
    private fun llvmType(type: JasType?): String {
        return when (type) {
            // 按 Jasper 原始类型名做字面映射；未列出的原始类型名走 else 兜底 i32。
            is JasPrimitiveType -> when (type.name) {
                "int32" -> "i32"
                "int64" -> "i64"
                "float32" -> "float"
                "float64" -> "double"
                "bool" -> "i1"
                "byte" -> "i8"
                else -> "i32"
            }
            is JasUnitType -> "void"
            // 字符串 / Any / 命名类型都退化为不透明指针 i8*：当前无布局与结构信息。
            is JasStringType -> "i8*"
            is JasAnyType -> "i8*"
            is JasNamedType -> "i8*"
            // null 类型与任何未覆盖类型统一兜底 i32（可能失真）。
            else -> "i32"
        }
    }

    /**
     * 表达式 -> LLVM 类型：先 inferType 推断 JasType，再走上文的 llvmType 映射。
     *
     * 已知局限：它是纯启发式——inferType 判定不出时会回退到 int32，因此任何
     *   复杂表达式都会得到 i32，而不是报错。
     */
    private fun llvmType(expr: JasExpression): String = llvmType(inferType(expr))

    /**
     * 表达式 -> LLVM 常量文本。
     *
     * 做什么：仅覆盖字面量——int / float 直接 toString，bool 转 "1"/"0"，
     *   null 转 "null"；非字面量表达式一律兜底为 "0"。
     *
     * 已知局限：字符串字面量**没有**生成 i8* 常量（会落到兜底得到 "0"），可能与
     *   它被推断出的类型（i8*）不一致，从而产出非法 / 无意义的 IR。
     */
    private fun llvmValue(expr: JasExpression): String {
        // 非字面量表达式统一兜底为 "0"（语义不保证，见上方说明）。
        return when (expr) {
            is JasIntLiteral -> expr.value.toString()
            is JasFloatLiteral -> expr.value.toString()
            is JasBoolLiteral -> if (expr.value) "1" else "0"
            is JasNullLiteral -> "null"
            else -> "0"
        }
    }

    /**
     * 从表达式**启发式**推断 Jasper 类型（不查符号表）。
     *
     * 做什么：按字面量种类给出类型——整型字面量->int32（即使数值溢出 int32 也
     *   不会升为 int64）、浮点字面量->float32（不区分 float64）、字符串->
     *   JasStringType、布尔->bool、null->JasAnyType。
     *
     * 兜底：其它表达式一律当 int32。
     *
     * 已知局限：这是纯语法启发式，不参考声明 / 参数 / 符号表，故变量引用、调用、
     *   运算等都会被判为 int32；之所以当前够用，只因只对 return 的字面量取值。
     */
    private fun inferType(expr: JasExpression): JasType? {
        return when (expr) {
            // 整型一律 int32，不按数值大小选择 int64。
            is JasIntLiteral -> JasPrimitiveType("int32")
            // 浮点一律 float32，不区分 float32/float64。
            is JasFloatLiteral -> JasPrimitiveType("float32")
            is JasStringLiteral -> JasStringType
            is JasBoolLiteral -> JasPrimitiveType("bool")
            is JasNullLiteral -> JasAnyType
            // 兜底：无法识别的表达式一律当 int32（启发式，可能失真）。
            else -> JasPrimitiveType("int32")
        }
    }
}
